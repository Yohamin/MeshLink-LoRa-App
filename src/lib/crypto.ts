import { gcm } from "@noble/ciphers/aes.js";
import {
  CryptoDigestAlgorithm,
  CryptoEncoding,
  digestStringAsync,
  getRandomBytes,
} from "expo-crypto";

const AES_128_HEX_LENGTH = 32;
const AES_128_PAYLOAD_PREFIX = "M2:";
const GCM_NONCE_LENGTH = 12;
const GCM_TAG_LENGTH = 16;

export type CryptoOperationMetrics = {
  plaintextSizeBytes: number;
  ciphertextSizeBytes: number;
  encodedCiphertextSizeBytes: number;
  operationTimeUs: number;
  success: boolean;
};

type MetricsCallback = (metrics: CryptoOperationMetrics) => void;

function highResolutionTimeUs(): number {
  return Math.round(performance.now() * 1000);
}

async function keyDigest(passphrase: string): Promise<string> {
  return digestStringAsync(
    CryptoDigestAlgorithm.SHA256,
    `LoRaMesh/v1/${passphrase}`,
    { encoding: CryptoEncoding.HEX },
  );
}

async function keyFromPassphrase(
  passphrase: string,
  size: 128 | 256,
): Promise<Uint8Array> {
  const digest = await keyDigest(passphrase);
  const keyHex = size === 128 ? digest.slice(0, AES_128_HEX_LENGTH) : digest;
  return hexToBytes(keyHex);
}

function hexToBytes(value: string): Uint8Array {
  if (value.length % 2 !== 0) throw new Error("Longitud hexadecimal no válida.");
  const bytes = new Uint8Array(value.length / 2);
  for (let index = 0; index < bytes.length; index += 1) {
    bytes[index] = Number.parseInt(value.slice(index * 2, index * 2 + 2), 16);
  }
  return bytes;
}

function base64ToBytes(value: string): Uint8Array {
  const binary = atob(value);
  return Uint8Array.from(binary, (character) => character.charCodeAt(0));
}

function bytesToBase64(value: Uint8Array): string {
  let binary = "";
  for (const byte of value) binary += String.fromCharCode(byte);
  return btoa(binary);
}

export async function networkKeyId(passphrase: string): Promise<string> {
  const digest = (await keyDigest(passphrase)).toUpperCase().slice(0, 12);
  return digest.match(/.{1,4}/g)?.join("-") ?? digest;
}

export async function testEncryptionRoundTrip(passphrase: string): Promise<boolean> {
  const expected = "MeshLink AES self-test";
  const encrypted = await encryptMessage(expected, passphrase);
  const decrypted = await decryptMessage(encrypted, passphrase);
  return decrypted === expected;
}

export async function encryptMessage(
  plainText: string,
  passphrase: string,
  onMetrics?: MetricsCallback,
): Promise<string> {
  const key = await keyFromPassphrase(passphrase, 128);
  const nonce = getRandomBytes(GCM_NONCE_LENGTH);
  const plaintext = new TextEncoder().encode(plainText);
  const startedAtUs = highResolutionTimeUs();
  const encrypted = gcm(key, nonce).encrypt(plaintext);
  const encryptionTimeUs = highResolutionTimeUs() - startedAtUs;
  const combined = new Uint8Array(nonce.length + encrypted.length);
  combined.set(nonce);
  combined.set(encrypted, nonce.length);
  const payload = `${AES_128_PAYLOAD_PREFIX}${bytesToBase64(combined)}`;
  onMetrics?.({
    plaintextSizeBytes: plaintext.length,
    ciphertextSizeBytes: combined.length,
    encodedCiphertextSizeBytes: payload.length,
    operationTimeUs: encryptionTimeUs,
    success: true,
  });
  return payload;
}

export async function decryptMessage(
  payload: string,
  passphrase: string,
  onMetrics?: MetricsCallback,
): Promise<string> {
  const isAes128 = payload.startsWith(AES_128_PAYLOAD_PREFIX);
  const encodedPayload = isAes128
    ? payload.slice(AES_128_PAYLOAD_PREFIX.length)
    : payload;
  // Unprefixed packets were generated by MeshLink v1 with AES-256-GCM.
  const key = await keyFromPassphrase(passphrase, isAes128 ? 128 : 256);
  const combined = base64ToBytes(encodedPayload);
  if (combined.length < GCM_NONCE_LENGTH + GCM_TAG_LENGTH) {
    onMetrics?.({
      plaintextSizeBytes: 0,
      ciphertextSizeBytes: combined.length,
      encodedCiphertextSizeBytes: payload.length,
      operationTimeUs: 0,
      success: false,
    });
    throw new Error("El mensaje cifrado está incompleto.");
  }
  const nonce = combined.slice(0, GCM_NONCE_LENGTH);
  const encrypted = combined.slice(GCM_NONCE_LENGTH);
  const plaintextSizeBytes = encrypted.length - GCM_TAG_LENGTH;
  const startedAtUs = highResolutionTimeUs();
  let plaintext: Uint8Array;
  try {
    plaintext = gcm(key, nonce).decrypt(encrypted);
  } catch (error) {
    onMetrics?.({
      plaintextSizeBytes,
      ciphertextSizeBytes: combined.length,
      encodedCiphertextSizeBytes: payload.length,
      operationTimeUs: highResolutionTimeUs() - startedAtUs,
      success: false,
    });
    throw error;
  }
  onMetrics?.({
    plaintextSizeBytes: plaintext.length,
    ciphertextSizeBytes: combined.length,
    encodedCiphertextSizeBytes: payload.length,
    operationTimeUs: highResolutionTimeUs() - startedAtUs,
    success: true,
  });
  return new TextDecoder().decode(plaintext);
}
